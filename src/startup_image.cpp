#define BAR_X          0
#define BAR_Y          38
#define BAR_W          84
#define BAR_H          9

#define BOX_START_X    2
#define BOX_Y          40

#define BOX_W          3
#define BOX_GAP        2

#define BOX_COUNT      15


// ============================================================
// CURRENT PROGRESS
// 0  = empty
// 27 = full
// ============================================================

static uint8_t loadingProgress = 0;

static bool startupLoading = false;


// ============================================================
// DRAW STARTUP
// ============================================================

static void drawStartupFrame()
{
    display.clearDisplay();


    // Startup image
    display.drawBitmap(
        0,
        0,
        startupImage1,
        84,
        48,
        BLACK
    );


    // Outer border
    display.drawRect(
        BAR_X,
        BAR_Y,
        BAR_W,
        BAR_H,
        WHITE
    );


    // ========================================================
    // DRAW BOXES
    // ========================================================

    for (uint8_t i = 0; i < BOX_COUNT; i++)
    {
        int x =
            BOX_START_X +
            i * (BOX_W + BOX_GAP);


        if (i < loadingProgress)
        {
            // Filled box
            display.fillRect(
                x,
                BOX_Y,
                BOX_W,
                5,
                WHITE
            );
        }
        else
        {
            // Empty box
            display.drawRect(
                x,
                BOX_Y,
                BOX_W,
                1,
                BLACK
            );
        }
    }


    display.display();
}


// ============================================================
// START
// ============================================================

void showStartupImages()
{
    startupLoading = true;

    loadingProgress = 0;

    drawStartupFrame();
}


// ============================================================
// SET PROGRESS
//
// percent = 0..100
// ============================================================

void setStartupProgress(
    uint8_t percent
)
{
    if (percent > 100)
        percent = 100;


    loadingProgress =
        (percent * BOX_COUNT) / 100;


    drawStartupFrame();
}


// ============================================================
// UPDATE
// ============================================================

void updateStartupLoading()
{
    if (!startupLoading)
        return;
}


// ============================================================
// STARTUP DELAY
// ============================================================

void startupDelay(
    unsigned long duration
)
{
    unsigned long start =
        millis();


    while (
        millis() - start <
        duration
    )
    {
        delay(5);
    }
}


// ============================================================
// STOP
// ============================================================

void stopStartupLoading()
{
    startupLoading = false;
}


// ============================================================
// STATUS
// ============================================================

bool isStartupLoading()
{
    return startupLoading;
}
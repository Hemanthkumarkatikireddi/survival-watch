const int FONT_COUNT =
    sizeof(fontTable) / sizeof(fontTable[0]);


// ============================================================
// FIND CHARACTER
// ============================================================

const Glyph* findGlyph(char c)
{
    for (int i = 0; i < FONT_COUNT; i++)
    {
        if (fontTable[i].character == c)
        {
            return &fontTable[i];
        }
    }

    return nullptr;
}


// ============================================================
// DRAW CHARACTER
// ============================================================

void drawWatchChar(
    int x,
    int y,
    char c,
    uint8_t scale
)
{
    const Glyph* glyph =
        findGlyph(c);


    if (glyph == nullptr)
    {
        return;
    }


    for (int row = 0; row < 7; row++)
    {
        for (int col = 0; col < 5; col++)
        {
            if (
                glyph->rows[row] &
                (1 << (4 - col))
            )
            {
                display.fillRect(
                    x + col * scale,
                    y + row * scale,
                    scale,
                    scale,
                    BLACK
                );
            }
        }
    }
}


// ============================================================
// DRAW TEXT
// ============================================================

void drawWatchText(
    int x,
    int y,
    const char* text,
    uint8_t scale
)
{
    if (text == nullptr)
    {
        return;
    }


    while (*text)
    {
        drawWatchChar(
            x,
            y,
            *text,
            scale
        );


        x += (6 * scale);

        text++;
    }
}


// ============================================================
// TEXT WIDTH
// ============================================================

int watchTextWidth(
    const char* text,
    uint8_t scale
)
{
    if (text == nullptr)
    {
        return 0;
    }


    int count = 0;


    while (*text)
    {
        count++;
        text++;
    }


    return count * 6 * scale;
}


// ============================================================
// BOLD DIGIT
// ============================================================

void drawBoldDigit(
    int x,
    int y,
    int digit,
    uint8_t scale
)
{
    if (digit < 0 || digit > 9)
    {
        return;
    }


    drawWatchChar(
        x,
        y,
        '0' + digit,
        scale
    );
}


// ============================================================
// BOLD COLON
// ============================================================

void drawBoldColon(
    int x,
    int y,
    uint8_t scale
)
{
    drawWatchChar(
        x,
        y,
        ':',
        scale
    );
}


// ============================================================
// BOLD TIME
// ============================================================

void drawBoldTime(
    int x,
    int y,
    int hour,
    int minute
)
{
    if (hour < 0)
        hour = 0;

    if (hour > 99)
        hour = 99;

    if (minute < 0)
        minute = 0;

    if (minute > 59)
        minute = 59;


    int h1 = hour / 10;
    int h2 = hour % 10;

    int m1 = minute / 10;
    int m2 = minute % 10;


    // ========================================================
    // LARGE DIGITAL TIME
    // ========================================================

    const uint8_t SCALE = 2;


    drawBoldDigit(
        x,
        y,
        h1,
        SCALE
    );


    x += 12;


    drawBoldDigit(
        x,
        y,
        h2,
        SCALE
    );


    x += 12;


    drawBoldColon(
        x,
        y,
        SCALE
    );


    x += 12;


    drawBoldDigit(
        x,
        y,
        m1,
        SCALE
    );


    x += 12;


    drawBoldDigit(
        x,
        y,
        m2,
        SCALE
    );
}
void drawDateText(
    int x,
    int y,
    const char* text
)
{
    if (text == nullptr)
        return;

    int charIndex = 0;

    while (*text)
    {
        char c = *text;

        // ====================================================
        // DRAW CHARACTER
        // ====================================================

        if (c >= '0' && c <= '9')
        {
            const SmallNumberGlyph* glyph =
                findSmallNumber(c);

            if (glyph != nullptr)
            {
                for (int row = 0; row < 7; row++)
                {
                    for (int col = 0; col < 5; col++)
                    {
                        if (
                            glyph->rows[row] &
                            (1 << (4 - col))
                        )
                        {
                            int newX;

                            if (col <= 1)
                                newX = 0;
                            else if (col == 2)
                                newX = 1;
                            else if (col == 3)
                                newX = 2;
                            else
                                newX = 3;

                            display.drawPixel(
                                x + newX,
                                y + row,
                                BLACK
                            );
                        }
                    }
                }
            }
        }
        else
        {
            const Glyph* glyph =
                findGlyph(c);

            if (glyph != nullptr)
            {
                for (int row = 0; row < 7; row++)
                {
                    for (int col = 0; col < 5; col++)
                    {
                        if (
                            glyph->rows[row] &
                            (1 << (4 - col))
                        )
                        {
                            int newX;

                            if (col <= 1)
                                newX = 0;
                            else if (col == 2)
                                newX = 1;
                            else if (col == 3)
                                newX = 2;
                            else
                                newX = 3;

                            display.drawPixel(
                                x + newX,
                                y + row,
                                BLACK
                            );
                        }
                    }
                }
            }
        }

        // ====================================================
        // CHARACTER SPACING
        // ====================================================

        x += 5;

        // Use the available extra space as
        // additional separation between selected characters.
        //
        // This keeps letters from touching.

        if (charIndex == 3 ||   // after 2026
            charIndex == 7 ||   // after SEP:
            charIndex == 10 ||  // after 12
            charIndex == 14)    // after SAT
        {
            x += 1;
        }

        charIndex++;
        text++;
    }
}
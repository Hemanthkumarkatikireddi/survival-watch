// ============================================================
// DRAW BOLD CHARACTER
// ============================================================

void drawBoldWatchChar(
    int x,
    int y,
    char c,
    uint8_t scale,
    uint8_t color
)
{
    if (scale == 0)
    {
        return;
    }

    const BoldGlyph* glyph =
        findBoldGlyph(c);

    if (glyph == nullptr)
    {
        return;
    }

    for (int row = 0; row < 7; row++)
    {
        for (int col = 0; col < 7; col++)
        {
            if (
                glyph->rows[row] &
                (1U << (6 - col))
            )
            {
                display.fillRect(
                    x + (col * scale),
                    y + (row * scale),
                    scale,
                    scale,
                    color
                );
            }
        }
    }
}


// ============================================================
// DRAW BOLD TEXT
// ============================================================
//
// 7 px glyph
// 1 px gap
// 8 px advance
//
// ============================================================

void drawBoldWatchText(
    int x,
    int y,
    const char* text,
    uint8_t scale,
    uint8_t color
)
{
    if (text == nullptr || scale == 0)
    {
        return;
    }

    while (*text)
    {
        drawBoldWatchChar(
            x,
            y,
            *text,
            scale,
            color
        );

        // 7 px glyph + 1 px gap
        x += 8 * scale;

        text++;
    }
}


// ============================================================
// FIND BOLD GLYPH
// ============================================================

static const BoldGlyph* findBoldGlyph(char c)
{
    for (size_t i = 0;
         i < sizeof(boldFontTable) / sizeof(boldFontTable[0]);
         i++)
    {
        if (boldFontTable[i].character == c)
        {
            return &boldFontTable[i];
        }
    }

    return nullptr;
}

// ============================================================
// NORMAL TEXT WIDTH
// ============================================================

int watchTextWidth(
    const char* text,
    uint8_t scale
)
{
    if (text == nullptr)
    {
        return 0;
    }

    int count = 0;

    while (*text)
    {
        count++;
        text++;
    }

    return count * 6 * scale;
}



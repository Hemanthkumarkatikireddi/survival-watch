const int FONT_COUNT =
    sizeof(fontTable) /
    sizeof(fontTable[0]);


// ============================================================
// FIND NORMAL GLYPH
// ============================================================

const Glyph* findGlyph(
    char c
)
{
    for (
        int i = 0;
        i < FONT_COUNT;
        i++
    )
    {
        if (
            fontTable[i].character == c
        )
        {
            return &fontTable[i];
        }
    }

    return nullptr;
}


// ============================================================
// FIND SMALL NUMBER
// ============================================================

const SmallNumberGlyph* findSmallNumber(
    char c
)
{
    for (
        int i = 0;
        i < SMALL_NUMBER_COUNT;
        i++
    )
    {
        if (
            smallNumberTable[i].character == c
        )
        {
            return &smallNumberTable[i];
        }
    }

    return nullptr;
}


// ============================================================
// DRAW SECONDS DIGIT
// ============================================================

void drawSecondsDigit(
    int x,
    int y,
    int digit
)
{
    if (
        digit < 0 ||
        digit > 9
    )
    {
        return;
    }

    const Glyph* glyph =
        findGlyph('0' + digit);

    if (glyph == nullptr)
    {
        return;
    }

    for (int row = 0; row < 7; row++)
    {
        for (int col = 0; col < 5; col++)
        {
            if (
                glyph->rows[row] &
                (1 << (4 - col))
            )
            {
                display.drawPixel(
                    x + col,
                    y + row,
                    BLACK
                );
            }
        }
    }
}


// ============================================================
// DRAW NORMAL CHARACTER
// ============================================================

void drawWatchChar(
    int x,
    int y,
    char c,
    uint8_t scale,
    uint8_t color
)
{
    // ========================================================
    // SMALL NUMBERS
    // ========================================================

    if (
        scale == 1 &&
        c >= '0' &&
        c <= '9'
    )
    {
        const SmallNumberGlyph* glyph =
            findSmallNumber(c);

        if (glyph == nullptr)
        {
            return;
        }

        for (int row = 0; row < 7; row++)
        {
            for (int col = 0; col < 5; col++)
            {
                if (
                    glyph->rows[row] &
                    (1 << (4 - col))
                )
                {
                    display.fillRect(
                        x + col,
                        y + row,
                        1,
                        1,
                        color
                    );
                }
            }
        }

        return;
    }


    // ========================================================
    // NORMAL FONT
    // ========================================================

    const Glyph* glyph =
        findGlyph(c);

    if (glyph == nullptr)
    {
        return;
    }

    for (int row = 0; row < 7; row++)
    {
        for (int col = 0; col < 5; col++)
        {
            if (
                glyph->rows[row] &
                (1 << (4 - col))
            )
            {
                display.fillRect(
                    x + (col * scale),
                    y + (row * scale),
                    scale,
                    scale,
                    color
                );
            }
        }
    }
}


// ============================================================
// DRAW NORMAL TEXT
// ============================================================

void drawWatchText(
    int x,
    int y,
    const char* text,
    uint8_t scale,
    uint8_t color
)
{
    if (text == nullptr)
    {
        return;
    }

    while (*text)
    {
        drawWatchChar(
            x,
            y,
            *text,
            scale,
            color
        );

        // 5 px glyph + 1 px gap
        x += (6 * scale);

        text++;
    }
}



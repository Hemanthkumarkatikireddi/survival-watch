// ============================================================
// MAIN LARGE TIME
// ============================================================
//
// Position remains:
//
// X = supplied x
// Y = supplied y
//
// Scale = 2
//
// ============================================================

void drawBoldTime(
    int x,
    int y,
    int hour,
    int minute
)
{
    if (hour < 0)
        hour = 0;

    if (hour > 99)
        hour = 99;

    if (minute < 0)
        minute = 0;

    if (minute > 59)
        minute = 59;


    int h1 = hour / 10;
    int h2 = hour % 10;

    int m1 = minute / 10;
    int m2 = minute % 10;


    const uint8_t SCALE = 2;


    // --------------------------------------------------------
    // HH:MM
    // --------------------------------------------------------

    drawBoldDigit(
        x,
        y,
        h1,
        SCALE
    );

    x += 12;


    drawBoldDigit(
        x,
        y,
        h2,
        SCALE
    );

    x += 12;


    drawBoldColon(
        x,
        y,
        SCALE
    );

    x += 12;


    drawBoldDigit(
        x,
        y,
        m1,
        SCALE
    );

    x += 12;


    drawBoldDigit(
        x,
        y,
        m2,
        SCALE
    );
}


